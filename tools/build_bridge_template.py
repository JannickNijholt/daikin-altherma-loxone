#!/usr/bin/env python3
"""Generate the Loxone Modbus template and register docs for the Onecta → Modbus bridge.

Usage: python3 tools/build_bridge_template.py [--check]

Source of truth: src/onecta_modbus/registers.py. Writes
  loxone/templates/MB_Onecta_Bridge.xml       registers tagged "main" (heating units)
  loxone/templates/MB_Onecta_Bridge_full.xml  every register
  docs/bridge-registers.md                    register table
"""

from __future__ import annotations

import sys
from pathlib import Path
from xml.etree import ElementTree
from xml.sax.saxutils import quoteattr

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from onecta_modbus.registers import HOLDING, REGISTERS, Register  # noqa: E402

UNIT_ID = 1
MIN_LOXONE_VERSION = "15000227"
INT16, UINT16 = 33, 32
READ_HOLDING, READ_INPUT, WRITE_SINGLE = 3, 4, 6

UNIT_FORMAT = {"°C": "<v.1>°C", "kWh": "<v.1> kWh", "s": "<v> s", "": "<v>"}


def attrs(**values: object) -> str:
    return " ".join(f"{k}={quoteattr(str(v), {chr(10): '&#10;'})}" for k, v in values.items() if v is not None)


def loxone_unit(reg: Register) -> str:
    if reg.unit == "°C" and reg.scale == 1:
        return "<v>°C"
    return UNIT_FORMAT.get(reg.unit, f"<v> {reg.unit}")


def scaling(reg: Register, sensor: bool) -> dict:
    if reg.scale == 1:
        return {"SourceValHigh": 100, "DestValHigh": 100}
    return {"SourceValHigh": reg.scale, "DestValHigh": 1} if sensor else {"SourceValHigh": 1, "DestValHigh": reg.scale}


def command(reg: Register, function: int, sensor: bool) -> str:
    prefix = "HR" if reg.table == HOLDING else "IR"
    suffix = " (state)" if reg.table == HOLDING and sensor else ""
    address = reg.offset - 1
    return "\t<ModbusCmd " + attrs(
        Title=f"{prefix}{reg.offset:02d} {reg.name}{suffix}",
        Comment=f"Onecta bridge register {prefix}{reg.offset}",
        HintText=reg.hint or None,
        ModbusAddress=address if address else None,
        ModbusCmd=function,
        ModbusDataType=UINT16 if reg.unsigned else INT16,
        ModbusPollingCycle=reg.poll if sensor else None,
        Unit=loxone_unit(reg),
        Analog="true",
        Sensor="true" if sensor else "false",
        **scaling(reg, sensor),
        # The bridge only acts on changed values, so periodic re-sending isn't needed.
        RepeatRate=None if sensor else 0,
    ) + "/>"


def template(registers: list[Register], title: str) -> str:
    hint = ("Daikin Onecta → Modbus bridge (HomeHub-compatible map). Address: bridge IP, port 502. "
            "Unit ID per heat pump as shown in the bridge web UI. Raw 32766 = no data, 32767 = unsupported.")
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f"<Modbus {attrs(Title=title, Comment='', HintText=hint, Channel=UNIT_ID)}>",
             f'\t<Info templateType="7" minVersion="{MIN_LOXONE_VERSION}"/>']
    ordered = sorted(registers, key=lambda r: (r.table == HOLDING, r.offset))
    lines += [command(r, READ_INPUT, True) for r in ordered if r.table != HOLDING]
    lines += [command(r, READ_HOLDING, True) for r in ordered if r.table == HOLDING and r.readback]
    lines += [command(r, WRITE_SINGLE, False) for r in ordered if r.table == HOLDING and r.write]
    lines.append("</Modbus>")
    return "\n".join(lines) + "\n"


def markdown() -> str:
    rows = ["| Register | PDU address | Name | Scale | Unit | Write | Notes |", "|---|---|---|---|---|---|---|"]
    for reg in sorted(REGISTERS, key=lambda r: (r.table != HOLDING, r.offset)):
        prefix = "HR" if reg.table == HOLDING else "IR"
        scale = f"x{reg.scale}" if reg.scale != 1 else ("text16" if reg.unsigned else "")
        notes = reg.hint.replace("\n", "; ")
        ext = " *(ext)*" if reg.extension else ""
        rows.append(f"| {prefix}{reg.offset}{ext} | {reg.offset - 1} | {reg.name} | {scale} | {reg.unit} | "
                    f"{'yes' if reg.write else ''} | {notes} |")
    return ("# Onecta → Modbus bridge: register map\n\n"
            "Generated by `tools/build_bridge_template.py` from `src/onecta_modbus/registers.py`.\n\n"
            "- Registers 1–99 use the Daikin HomeHub (EKRHH) use case 3 layout; *(ext)* = bridge extension.\n"
            "- PDU address = register − 1. All values are signed 16-bit unless noted.\n"
            "- Raw `32766` = no data for this unit, `32767` = register not supported.\n"
            "- Holding registers read back the current Daikin cloud value.\n\n" + "\n".join(rows) + "\n")


OUTPUTS = {
    ROOT / "loxone/templates/MB_Onecta_Bridge.xml": lambda: template(
        [r for r in REGISTERS if "main" in r.tags], "Daikin Onecta bridge (heating)"),
    ROOT / "loxone/templates/MB_Onecta_Bridge_full.xml": lambda: template(REGISTERS, "Daikin Onecta bridge (full)"),
    ROOT / "docs/bridge-registers.md": markdown,
}


def main() -> int:
    stale = []
    for path, build in OUTPUTS.items():
        content = build()
        if path.suffix == ".xml":
            ElementTree.fromstring(content.encode())  # must be well-formed
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8-sig") != content:
                stale.append(path.name)
        else:
            path.write_text(content, encoding="utf-8-sig" if path.suffix == ".xml" else "utf-8")
            print(f"Wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date, run tools/build_bridge_template.py: " + ", ".join(stale))
        return 1
    if "--check" in sys.argv:
        print("OK: bridge templates and docs are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
